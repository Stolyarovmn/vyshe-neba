"""Схемы массы объектов E0 (v2) в проекции island_top_3_4.

Правило v2 (отзыв владельца по попытке BI_CONTROL attempt02: «крыша занимает слишком много места, интересной должна быть не крыша, а наполнение»):
камера 73,44° сжимает стены до cos 73,44° ≈ 0,285 высоты, поэтому здание под ней читается плоскостью. Значит:
  * закрытый объём узкий: верхняя плоскость (крыша) <= 40 % площади основания всего спрайта;
  * то, ради чего объект куплен, лежит на горизонтальных плоскостях: на крыше-плите, на дворе, на путях;
  * плита основания не шире содержимого (нет пустого бетона).
Использует Scene из e0_massing.py. Запуск:  python e0_massing_objects.py control|logistics|recovery|factory <out.png> [out.json]
"""
import json
import sys

from e0_massing import FAR, S, Scene

STEEL = ((150, 158, 138), (112, 120, 100))
BEAM = ((176, 176, 170), (120, 120, 116))
DARK = ((110, 110, 108), (86, 86, 84))
WOOD = ((186, 146, 90), (140, 108, 66))
CONC = ((176, 174, 166), (148, 146, 138))
YEL = ((200, 170, 70), (170, 142, 56))


def _meta(sc, jpath, slab, W, roof_share=None):
    """Углы плиты и отношения кромок для приёмки исходника (см. art/docs/E0_CLAUDE_PROMPT_STYLE.md)."""
    x0, x1, y0, y1, z = slab
    c = {'far_left': sc.p(x0, y0, z), 'far_right': sc.p(x1, y0, z), 'near_left': sc.p(x0, y1, z), 'near_right': sc.p(x1, y1, z)}
    far = c['far_right'][0] - c['far_left'][0]
    near = c['near_right'][0] - c['near_left'][0]
    depth = c['near_left'][1] - c['far_left'][1]
    meta = {'projection': 'island_top_3_4 proxy 73.44deg', 'k_px_per_m': sc.k, 'slab_corners_px': c, 'far_over_near': far / near,
            'depth_over_mean_width': depth / ((far + near) / 2), 'expected_depth_over_mean_width': ((y1 - y0) * S) / (W * (1 + FAR) / 2),
            'roof_share_of_slab_target_max': 0.40, 'roof_share_of_slab_schema': roof_share}
    if jpath:
        json.dump(meta, open(jpath, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)


def control(path, jpath=None):
    """BI-CONTROL E0 v2: узкая рубка с плитой-крышей (антенна телеметрии, вытяжка, люк), кабельная траншея с плитами и два вводных шкафа."""
    sc = Scene(5.0)
    sc.box(-3.4, 3.4, -2.4, 2.4, 0, 0.10, *CONC, order=-5)                                  # бетонная плита двора
    sc.box(-2.1, 2.1, -1.85, 0.65, 0.10, 0.30, (168, 166, 158), (140, 138, 132), order=-4)  # цоколь
    sc.box(-1.9, 1.9, -1.7, 0.50, 0.30, 3.00, (206, 206, 196), (150, 158, 138), order=-3)  # рубка 3.8 x 2.2 м, плита-крыша
    sc.front_decal(0.9, 1.8, 0.51, 0.30, 2.30, (100, 80, 60), 0.6)                         # дверь 0.9 x 2.0
    sc.front_decal(-0.8, 0.2, 0.51, 1.2, 2.0, (70, 90, 110), 0.6)                           # окно с решёткой
    sc.front_decal(-1.7, -1.0, 0.51, 1.8, 2.5, (96, 96, 96), 0.6)                           # жалюзи
    sc.box(1.15, 1.55, 0.50, 0.80, 2.45, 2.75, (240, 190, 90), (210, 160, 70), order=0.8)   # лампа в сетке над дверью
    sc.box(-1.45, -1.15, -1.40, -1.10, 3.00, 4.80, *BEAM, order=0.9)                        # мачта приёма телеметрии (от ракеты)
    sc.box(-1.75, -0.80, -1.65, -0.85, 4.80, 4.95, *STEEL, order=0.95)                      # тарелка на мачте
    sc.box(1.30, 1.70, -1.45, -1.05, 3.00, 3.80, *BEAM, order=0.9)                          # вытяжка рубки
    sc.box(-0.20, 0.60, -1.15, -0.45, 3.00, 3.12, *DARK, order=0.7)                         # люк на крыше
    sc.box(-3.2, 3.2, 1.45, 1.85, 0.10, 0.14, (120, 120, 118), (90, 90, 88), order=1.0)     # кабельная траншея с плитами: от радара и поста
    sc.box(-3.2, -2.5, 1.20, 1.85, 0.10, 1.20, *STEEL, order=1.85)                          # вводной шкаф со стороны радара
    sc.box(2.5, 3.2, 1.20, 1.85, 0.10, 1.20, *STEEL, order=1.85)                            # вводной шкаф со стороны поста наблюдения
    sc.box(-1.55, -1.35, 0.50, 1.45, 0.10, 0.14, (120, 120, 118), (90, 90, 88), order=0.9)  # ответвление траншеи к стене рубки
    sc.render(path)
    _meta(sc, jpath, (-3.4, 3.4, -2.4, 2.4, 0.10), 6.8, roof_share=(3.8 * 2.2) / (6.8 * 4.8))


def logistics(path, jpath=None):
    """B07 E0 v2: портал из двух стоек и балки, тележка с ручной цепной талью, дощатая стоянка груза, ящики, приёмная площадка."""
    sc = Scene(3.0)
    sc.box(-3.6, 3.6, -1.5, 1.5, 0, 0.15, *CONC, order=-5)                                   # бетонная плита двора
    sc.box(-3.4, -1.5, -1.4, 0.3, 0.15, 0.40, (196, 160, 100), (150, 120, 76), order=-4)     # дощатый настил-стоянка груза
    sc.box(-3.2, -2.3, -1.2, -0.4, 0.40, 1.40, *WOOD, order=-0.4)                            # ящик 1
    sc.box(-2.3, -1.7, -1.2, -0.7, 0.40, 1.10, (180, 140, 86), (136, 104, 62), order=-0.7)   # ящик 2
    sc.box(1.9, 2.9, -0.5, 0.5, 0.15, 1.15, *WOOD, order=0.5)                                # ящик на приёмной площадке
    sc.box(-2.35, -2.05, -0.25, 0.05, 0.15, 3.25, *STEEL, order=0.05)                        # левая стойка портала
    sc.box(2.05, 2.35, -0.25, 0.05, 0.15, 3.25, *STEEL, order=0.05)                          # правая стойка
    sc.box(-2.45, 2.45, -0.20, 0.10, 3.25, 3.50, *BEAM, order=0.1)                           # балка портала
    sc.box(-0.55, 0.05, -0.30, 0.20, 3.00, 3.25, *YEL, order=0.2)                            # тележка
    sc.box(-0.50, 0.00, -0.25, 0.15, 2.35, 3.00, *STEEL, order=0.15)                         # корпус тали и ручное колесо
    sc.box(-0.30, -0.20, -0.05, 0.05, 1.30, 2.35, *DARK, order=0.05)                         # цепь и крюк
    sc.render(path)
    _meta(sc, jpath, (-3.6, 3.6, -1.5, 1.5, 0.15), 7.2, roof_share=0.0)


def recovery(path, jpath=None):
    """BI-RETURN E0 v2: люлька с резиновыми накладками, стойка со стрелой, ручная лебёдка, трос и крюк."""
    sc = Scene(3.4)
    sc.box(-3.5, 3.5, -1.6, 1.6, 0, 0.12, *CONC, order=-5)                                   # бетонная площадка
    sc.box(-1.7, 1.7, -0.95, -0.50, 0.12, 0.60, (70, 70, 72), (50, 50, 52), order=-0.5)      # дальняя резиновая опора люльки
    sc.box(-1.7, 1.7, 0.50, 0.95, 0.12, 0.60, (70, 70, 72), (50, 50, 52), order=0.95)        # ближняя резиновая опора
    sc.box(-1.35, -1.10, -0.95, 0.95, 0.12, 0.42, *STEEL, order=0.2)                         # поперечина слева
    sc.box(1.10, 1.35, -0.95, 0.95, 0.12, 0.42, *STEEL, order=0.2)                           # поперечина справа
    sc.box(2.25, 2.55, -0.35, -0.05, 0.12, 3.30, *STEEL, order=-0.05)                        # стойка
    sc.box(0.20, 2.55, -0.32, -0.08, 3.20, 3.45, *BEAM, order=-0.08)                         # стрела, вылет к центру люльки
    sc.box(0.12, 0.22, -0.25, -0.15, 0.85, 3.20, *DARK, order=-0.15)                         # трос
    sc.box(0.00, 0.34, -0.30, -0.06, 0.55, 0.90, *YEL, order=-0.06)                          # крюковая обойма
    sc.box(2.00, 2.95, 0.20, 0.95, 0.12, 0.85, *STEEL, order=0.95)                           # ручная лебёдка с барабаном
    sc.box(2.95, 3.35, 0.50, 0.62, 0.50, 0.66, (200, 120, 70), (170, 98, 56), order=0.62)    # рукоять
    sc.render(path)
    _meta(sc, jpath, (-3.5, 3.5, -1.6, 1.6, 0.12), 7.0, roof_share=0.0)


def factory(path, jpath=None):
    """BI-FACTORY E0 v2: узкий цех у дальнего края (скатная кровля к двору, раздвижные ворота, труба), перед ним открытый двор:
    рельсовый путь от ворот, секция ступени на двух седлах, поворотный кран-укосина с ручной талью."""
    sc = Scene(6.0)
    sc.box(-3.8, 3.8, -2.0, 3.0, 0, 0.08, *CONC, order=-5)                                   # площадка
    sc.box(-3.0, 3.0, -2.0, -0.15, 0.08, 0.30, (168, 166, 158), (140, 138, 132), order=-4)  # цоколь цеха
    sc.box(-2.85, 2.85, -1.9, -0.30, 0.30, 3.30, (206, 206, 196), (150, 158, 138), order=-3)    # стены цеха 5.7 x 1.6 м
    sc.quad([(-3.1, -0.10, 3.32), (3.1, -0.10, 3.32), (3.1, -2.1, 3.65), (-3.1, -2.1, 3.65)], (224, 224, 214), (-0.1, 3.3))  # скат к двору
    sc.box(-1.0, 1.0, -1.5, -0.95, 3.50, 4.00, (200, 200, 192), (140, 140, 134), order=0.5)   # коньковая вытяжка
    sc.box(2.2, 2.6, -1.8, -1.4, 3.50, 5.30, (196, 196, 190), (140, 140, 134), order=0.5)    # труба печи/термообработки
    sc.front_decal(-2.3, 0.1, -0.29, 0.30, 3.00, (100, 80, 60), -0.2)                          # раздвижные ворота 2.6 x 2.7 м
    sc.box(-2.5, 1.4, -0.30, -0.18, 3.05, 3.15, (120, 120, 118), (90, 90, 88), order=-0.18)  # рельс ворот
    sc.front_decal(1.5, 2.4, -0.29, 0.30, 2.30, (96, 74, 56), -0.2)                            # дверь персонала 0.9 x 2.0
    sc.box(2.5, 2.8, -0.30, -0.12, 1.10, 1.70, (214, 190, 80), (180, 160, 64), order=-0.12)  # кабельный ввод
    for i in range(7):                                                                         # шпалы пути от ворот к краю площадки
        y = -0.1 + i * 0.5
        sc.box(-2.15, -0.05, y, y + 0.2, 0.08, 0.12, (120, 100, 70), (90, 76, 54), order=0.2 + y)
    sc.box(-1.95, -1.85, -0.1, 3.0, 0.12, 0.18, *DARK, order=0.3)                              # рельс 1
    sc.box(-0.35, -0.25, -0.1, 3.0, 0.12, 0.18, *DARK, order=0.3)                              # рельс 2
    sc.box(1.0, 1.35, 1.85, 2.45, 0.08, 0.55, *STEEL, order=1.9)                               # седло 1
    sc.box(2.9, 3.25, 1.85, 2.45, 0.08, 0.55, *STEEL, order=1.9)                               # седло 2
    sc.box(0.9, 3.5, 1.75, 2.55, 0.55, 1.35, (214, 214, 204), (170, 170, 160), order=2.5)      # секция ступени 2.8 м на седлах
    sc.box(3.15, 3.45, 0.60, 0.90, 0.08, 3.30, *STEEL, order=0.9)                              # колонна крана-укосины
    sc.box(3.10, 3.50, 0.60, 2.30, 3.10, 3.30, *BEAM, order=1.0)                               # стрела над секцией
    sc.box(3.20, 3.40, 1.90, 2.10, 2.20, 3.10, *DARK, order=1.1)                              # ручная таль и крюк
    sc.render(path)
    _meta(sc, jpath, (-3.8, 3.8, -2.0, 3.0, 0.08), 7.6, roof_share=(6.2 * 2.0) / (7.6 * 5.0))


if __name__ == '__main__':
    kind, out = sys.argv[1], sys.argv[2]
    {'control': control, 'logistics': logistics, 'recovery': recovery, 'factory': factory}[kind](out, sys.argv[3] if len(sys.argv) > 3 else None)
