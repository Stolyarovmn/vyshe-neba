const ICONS = Object.fromEntries(
  Object.entries(RAW).map(([name, rows]) => {
    const fixed = rows.map((r) => (r + '............').slice(0, ICON_GRID));
    while (fixed.length < ICON_GRID) fixed.push('............');
    return [name, fixed.slice(0, ICON_GRID)];
  }),
);

export const ICON_NAMES = Object.keys(ICONS);
export const hasIcon = (name) => name in ICONS;

export function createIcons() {
  let dpr = 1;
  const cache = new Map();

  function bitmap(name, color, cell) {
    const key = `${name}|${color}|${cell}`;
    let canvas = cache.get(key);
    if (canvas) return canvas;
    const rows = ICONS[name] || ICONS.info;
    canvas = document.createElement('canvas');
    canvas.width = canvas.height = ICON_GRID * cell;
    const c = canvas.getContext('2d');
    const tones = { '#': color, '+': mix(color, '#ffffff', 0.42), '-': mix(color, '#000000', 0.42), k: '#05080f', w: '#ffffff' };
    rows.forEach((row, y) => {
      for (let x = 0; x < ICON_GRID; x++) {
        const tone = tones[row[x]];
        if (!tone) continue;
        c.fillStyle = tone;
        c.fillRect(x * cell, y * cell, cell, cell);
      }
    });
    cache.set(key, canvas);
    return canvas;
  }

  function setDpr(v) {
    if (v !== dpr) {
      dpr = v;
      cache.clear();
    }
  }

  /** Иконка по центру (cx, cy), номинальный размер size (CSS px) округляется до целых ячеек. */
  function draw(ctx, name, cx, cy, size, color = '#fff', alpha = 1) {
    const cell = Math.max(1, Math.round((size * dpr) / ICON_GRID));
    const bm = bitmap(name, color, cell);
    const actual = (ICON_GRID * cell) / dpr;
    const prevAlpha = ctx.globalAlpha;
    if (alpha !== 1) ctx.globalAlpha = prevAlpha * alpha;
    const prevSmooth = ctx.imageSmoothingEnabled;
    ctx.imageSmoothingEnabled = false;
    const x = Math.round((cx - actual / 2) * dpr) / dpr;
    const y = Math.round((cy - actual / 2) * dpr) / dpr;
    ctx.drawImage(bm, x, y, actual, actual);
    ctx.imageSmoothingEnabled = prevSmooth;
    if (alpha !== 1) ctx.globalAlpha = prevAlpha;
    return actual;
  }

  return { draw, setDpr };
}
