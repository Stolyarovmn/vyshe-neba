// ---------- сегментные цифры (табло, счётчики) ----------

// Семь сегментов: a верх, b правый верх, c правый низ, d низ, e левый низ, f левый верх, g середина.
const SEGMENTS = {
  0: 'abcdef', 1: 'bc', 2: 'abdeg', 3: 'abcdg', 4: 'bcfg', 5: 'acdfg', 6: 'acdefg', 7: 'abc', 8: 'abcdefg', 9: 'abcdfg', '-': 'g',
};

/** Размер знака сегментного шрифта при высоте h (пикселей устройства): ширина и шаг. */
export function segmentMetrics(h) {
  const t = Math.max(2, Math.round(h / 7));
  const w = Math.round(h * 0.56);
  return { w, h, t, advance: w + Math.max(2, Math.round(t * 1.4)) };
}

/**
 * Рисует число сегментными цифрами в точке (x, y) — левый верх, высота h (CSS px); ctx в CSS-пикселях.
 * lit — цвет горящих сегментов, ghost — цвет погашенных (если задан, рисуются все семь сегментов).
 * Возвращает ширину.
 */
export function drawSegments(ctx, str, x, y, h, lit, ghost) {
  const m = segmentMetrics(h);
  let cx = x;
  for (const ch of String(str)) {
    if (ch === '.' || ch === ',') {
      ctx.fillStyle = lit;
      ctx.fillRect(Math.round(cx), Math.round(y + h - m.t), m.t, m.t);
      cx += m.t + Math.max(2, Math.round(m.t * 0.8));
      continue;
    }
    if (ch === ':') {
      ctx.fillStyle = lit;
      ctx.fillRect(Math.round(cx), Math.round(y + h * 0.28), m.t, m.t);
      ctx.fillRect(Math.round(cx), Math.round(y + h * 0.66), m.t, m.t);
      cx += m.t + Math.max(2, Math.round(m.t * 0.8));
      continue;
    }
    if (ch === ' ' || ch === ' ') {
      cx += m.advance * 0.6;
      continue;
    }
    const on = SEGMENTS[ch] || '';
    const parts = {
      a: [m.t, 0, m.w - m.t * 2, m.t],
      d: [m.t, h - m.t, m.w - m.t * 2, m.t],
      g: [m.t, Math.round((h - m.t) / 2), m.w - m.t * 2, m.t],
      f: [0, m.t, m.t, Math.round((h - m.t * 3) / 2)],
      b: [m.w - m.t, m.t, m.t, Math.round((h - m.t * 3) / 2)],
      e: [0, Math.round(h / 2 + m.t / 2), m.t, Math.round((h - m.t * 3) / 2)],
      c: [m.w - m.t, Math.round(h / 2 + m.t / 2), m.t, Math.round((h - m.t * 3) / 2)],
    };
    for (const [key, r] of Object.entries(parts)) {
      const isOn = on.includes(key);
      if (!isOn && !ghost) continue;
      ctx.fillStyle = isOn ? lit : ghost;
      ctx.fillRect(Math.round(cx + r[0]), Math.round(y + r[1]), r[2], r[3]);
    }
    cx += m.advance;
  }
  return cx - x;
}

export function segmentWidth(str, h) {
  const m = segmentMetrics(h);
  let w = 0;
  for (const ch of String(str)) w += ch === '.' || ch === ',' || ch === ':' ? m.t + Math.max(2, Math.round(m.t * 0.8)) : ch === ' ' || ch === ' ' ? m.advance * 0.6 : m.advance;
  return Math.max(0, w - Math.max(2, Math.round(m.t * 1.4)));
}
