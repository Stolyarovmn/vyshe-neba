const TABLE = new Map();
for (const [k, v] of Object.entries({ ...LATIN, ...CYRILLIC, ...DIGITS, ...PUNCT })) TABLE.set(k, v);
for (const [cyr, lat] of Object.entries(CYR_LOOKALIKE)) TABLE.set(cyr, LATIN[lat]);

/** Приведение строки к тому, что умеет шрифт: заглавные, похожие знаки заменены. */
export function normalize(str) {
  return String(str ?? '')
    .toUpperCase()
    .replace(/[−–—]/g, '-')
    .replace(/…/g, '...')
    .replace(/[  ]/g, ' ')
    .replace(/№/g, 'N');
}

export const hasGlyph = (ch) => TABLE.has(ch);

/** Строки глифа или null для пробела и неизвестных символов. */
export function glyphRows(ch) {
  return TABLE.get(ch) || null;
}

/** Ширина символа в пикселях шрифта (с просветом). */
export function advanceOf(ch) {
  if (ch === ' ') return 4;
  if (ch === ' ') return 3;
  return ADVANCE;
}

/** Ширина строки в пикселях шрифта (без учёта масштаба). */
export function textUnits(str) {
  let w = 0;
  for (const ch of normalize(str)) w += advanceOf(ch);
  return Math.max(0, w - 1);
}

