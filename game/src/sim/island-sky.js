// Небо над островом на карте полёта. Карта рисуется под ракетой видом сверху-3/4, и «вверх» на экране — это и высота,
// и север острова: на старте предмет на высоте A виден над точкой карты в A единицах к северу от стола. Пока эта точка —
// суша, кольцо, монета или канистра выглядели бы лежащими на острове. Над островом остаются только облака (полупрозрачные,
// как туман), а предметы появляются выше северной кромки суши.
// Таблица собрана скриптом из маски game/assets/shared/island/start-island.land.json (topgen-20261111/gen_island_sky.py):
// NORTH[i] — самая северная суша, единицы над столом, в столбце x ∈ [X0 + i·STEP, X0 + (i+1)·STEP).

export const ISLAND_SKY = {
  X0: -250,
  STEP: 25,
  NORTH: [0, 74, 106, 106, 175, 180, 186, 170, 170, 170, 180, 180, 170, 164, 143, 164, 164, 191, 201, 217, 212, 228, 212, 201, 191, 196, 191, 164, 154, 154, 143, 143, 154, 148, 143, 164, 159, 164, 132, 164, 154, 148, 154, 138, 79, 58, 116, 116, 84, 0, 0],
};

const MARGIN = 14; // запас на видимый размер спрайта над его центром

/** Северная кромка суши (единицы над столом) на отрезке [x0, x1]; вне острова — 0. */
export function islandNorthEdge(x0, x1) {
  const { X0, STEP: S, NORTH } = ISLAND_SKY;
  let best = 0;
  const i0 = Math.max(0, Math.floor((x0 - X0) / S));
  const i1 = Math.min(NORTH.length - 1, Math.floor((x1 - X0) / S));
  for (let i = i0; i <= i1; i++) best = Math.max(best, NORTH[i]);
  return best;
}

/**
 * Будет ли предмет на (x, alt) с полушириной halfW и радиусом r виден над сушей острова. Проверка для худшего случая —
 * ракета на столе: с высотой карта мельчает и уходит вниз, и точка под предметом только удаляется от острова.
 * Запас по горизонтали 60 единиц — на сдвиг камеры за ракетой.
 */
export function overIsland(x, alt, halfW = 0, r = 0) {
  return alt - r - MARGIN < islandNorthEdge(x - halfW - 60, x + halfW + 60);
}
