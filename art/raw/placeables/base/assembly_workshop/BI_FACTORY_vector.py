"""Параметрический наружный цех: законченный пробный материал поверх точной геометрии."""
from E0_rigid_scene import RigidScene
import sys

grid='--grid' in sys.argv
s=RigidScene(width=320,height=256,scale=25,origin=(160,145)) if grid else RigidScene()
def front_quad(x0,x1,z0,z1,color,y=3.012):
    s.polygon([(x0,y,z0),(x1,y,z0),(x1,y,z1),(x0,y,z1)],color)

# Обшивка корпуса и опорная нижняя обвязка.
s.box(-4.5,4.5,-3,3,0,2.8,('#9ba69a','#89917c','#727e72'))
for i in range(20):
    x=-4.5+i*.45
    front_quad(x,x+.45,.12,2.72,['#929981','#969b83','#89917c'][i%3])
    s.line([(x,3.018,.15),(x,3.018,2.7)],'#b1b49a',2)
front_quad(-4.5,4.5,0,.15,'#626c66')
front_quad(-4.5,4.5,2.67,2.8,'#a7ac93')
for x in [-4.45,-.98,2.7,3.8,4.45]:
    front_quad(x-.055,x+.055,.05,2.75,'#72766a',3.025)

# Две створки грузовых ворот и отдельная человеческая дверь.
front_quad(-3.55,-1.05,0,2.46,'#343f42',3.03)
for x0,x1 in [(-3.5,-2.3),(-2.3,-1.1)]:
    front_quad(x0,x1,.045,2.4,'#687665',3.04)
    for x in [x0+.035,x1-.035]:
        s.line([(x,3.045,.08),(x,3.045,2.36)],'#a4ac8e',2)
    for z in [.1,2.34]:
        s.line([(x0+.03,3.045,z),(x1-.03,3.045,z)],'#4e6059',2)
for x in [-3.48,-1.12]:
    for z in [.4,1.95]:
        front_quad(x-.1,x+.1,z-.055,z+.055,'#a7aa91',3.055)
for x in [-2.40,-2.20]:
    s.line([(x,3.07,.95),(x,3.07,1.23),(x+.055,3.07,1.23)],'#c1b99c',3)
front_quad(2.75,3.75,0,2.05,'#344542',3.03)
front_quad(2.8,3.7,.035,2,'#5c6e61',3.04)
s.line([(3.35,3.06,1),(3.55,3.06,1)],'#b3af95',3)
for z in [.35,1.7]:
    front_quad(2.8,2.91,z-.045,z+.045,'#b0af92',3.06)

# Окно: рама для дневного света рабочего помещения, не дисплей.
front_quad(.25,2.05,.90,1.85,'#334751',3.04)
front_quad(.30,2.00,.96,1.79,'#58717c',3.05)
s.line([(.31,3.06,1.75),(1.97,3.06,1.75)],'#9eacaa',2)
s.line([(1.15,3.06,.96),(1.15,3.06,1.79)],'#8f9d94',2)

# Кабельный ввод низко у края фасада, вне дверного проёма.
front_quad(3.96,4.22,.15,.55,'#677e7b',3.04)
front_quad(4.01,4.17,.22,.48,'#3c555a',3.05)
s.line([(4.1,3.06,.22),(4.1,3.06,.02)],'#303d40',2)

# Крыша: ломаная плоскость и жёстко закреплённые кромки.
def roof_z(y): return 3.1-.3*abs(y)/3.2
for y0,y1,near in [(-3.2,0,False),(0,3.2,True)]:
    for i in range(21):
        x0=-4.7+i*(9.4/21); x1=x0+9.4/21
        color=(['#a8b2b4','#a3afb1','#aab4b5'] if not near else ['#899ba2','#8e9da3','#8799a0'])[i%3]
        s.polygon([(x0,y0,roof_z(y0)),(x1,y0,roof_z(y0)),(x1,y1,roof_z(y1)),(x0,y1,roof_z(y1))],color)
        # Приподнятый нахлёст листа, толщина 2 см в проектной модели.
        s.line([(x0+.035,y0,roof_z(y0)+.02),(x0+.035,y1,roof_z(y1)+.02)],'#c0c2b7',2)
        s.line([(x0+.065,y0,roof_z(y0)),(x0+.065,y1,roof_z(y1))],'#617580',2)
        for y in ([y0+.15,-1.5,y1-.15] if not near else [y0+.15,1.5,y1-.15]):
            s.disc(x0+.035,y,roof_z(y)+.025,.013,'#c5bca2')
        # Редкие связные сколы у кромки, не шум по всей поверхности.
        if i in [2,9,17]:
            y=y1-.12
            s.polygon([(x0+.1,y,roof_z(y)+.005),(x0+.2,y-.015,roof_z(y-.015)+.005),
                       (x0+.17,y-.055,roof_z(y-.055)+.005)],'#9a8069',outline=None,stroke=0)
for y in [-3.2,0,3.2]:
    s.line([(-4.7,y,roof_z(y)+.025),(4.7,y,roof_z(y)+.025)],'#c1c0ae',3)
    s.line([(-4.7,y+.015,roof_z(y)),(4.7,y+.015,roof_z(y))],'#4c626e',1)
for x in [-4.7,4.7]:
    s.line([(x,-3.2,2.8),(x,0,3.1),(x,3.2,2.8)],'#62757c',3)
for name,point in {'far_left':(-4.7,-3.2,2.8),'far_right':(4.7,-3.2,2.8),
 'near_right':(4.7,3.2,2.8),'near_left':(-4.7,3.2,2.8),'ground_anchor':(0,3,0)}.items():
    s.mark(name,point)
s.save('BI_FACTORY_vector_grid_source' if grid else 'BI_FACTORY_vector_source','Пробный цех E0: параметрическая геометрия и самостоятельный векторный материал. Не является принятой заменой imagegen-исходника.')
