"""Ручное грузовое место E0: метрический SVG и прямой экспорт в сетку."""
from math import cos,sin,pi
from E0_rigid_scene import RigidScene

s=RigidScene(width=320,height=256,scale=40,origin=(160,125),taper=.012)
steel=('#879b9b','#5c7075','#657c80')
# Тонкое основание: зона переноса грузов, не высокая декоративная сцена.
s.box(-3,3,-2,2,0,.06,('#979b8b','#747e76','#7b857a'))
s.line([(-2.95,-1.95,.065),(2.95,-1.95,.065)],'#b6b6a0',2)
for x in [-2.7,2.7]:
    for y in [-1.7,1.7]: s.disc(x,y,.065,.035,'#5c6c6a')

# Защищающие груз ящики стоят вне ног портала и прохода оператора.
for x0 in [-2.75,1.95]:
    x1=x0+.8; y0=.15; y1=.95; z=.78
    s.box(x0,x1,y0,y1,.06,z,('#a69674','#8b795a','#796c54'))
    for dx in [.2,.4,.6]:
        s.line([(x0+dx,y0,z+.005),(x0+dx,y1,z+.005)],'#786d54')
    for yy in [y0+.10,y1-.10]:
        s.line([(x0,yy,z+.015),(x1,yy,z+.015)],'#c0af84',3)
    for xx in [x0+.04,x1-.04]:
        s.line([(xx,y1,.12),(xx,y1,.74)],'#b7a47e',2)

# Рама: две симметричные А-опоры, опирающиеся на продольные лыжи.
def leg(x,y0,y1,z0,z1,color):
    s.polygon([(x-.075,y0,z0),(x+.075,y0,z0),
               (x+.075,y1,z1),(x-.075,y1,z1)],color)
    s.line([(x-.04,y0,z0),(x-.04,y1,z1)],'#adbaab',2)
for x in [-1.7,1.7]:
    s.box(x-.16,x+.16,-1.75,.35,.06,.16,('#7e9491','#52696c','#5e7477'))
    for y in [-1.62,.22]:
        for dx in [-.10,.10]: s.disc(x+dx,y,.165,.025,'#b2b49e')
    leg(x,-1.65,-.7,.16,2.5,'#708b88')
    leg(x,.25,-.7,.16,2.5,'#819890')
    s.line([(x,-1.18,1.3),(x,-.22,1.3)],'#8e9e8b',4)

# Балка с нижней полкой, крепится к обеим вершинам рамы.
s.box(-1.88,1.88,-.82,-.58,2.45,2.68,('#b1b9ad','#637e83','#738a8c'))
s.line([(-1.88,-.58,2.47),(1.88,-.58,2.47)],'#3f5e67',3)
for x in [-1.76,1.76]:
    s.box(x-.09,x+.09,-.86,-.54,2.48,2.7,('#879987','#617a72','#6d837a'))
    for y in [-.78,-.62]: s.disc(x,y,2.71,.028,'#b5b49b')

# Четыре колеса тележки несут таль на нижних полках балки.
for x in [-.22,.22]:
    for y in [-.82,-.58]:
        s.disc(x,y,2.48,.075,'#647c7c',normal='y')
s.box(-.30,.30,-.87,-.53,2.31,2.48,('#929c81','#6c7c67','#738672'))
# Защитный корпус ручного колеса и редуктора; механика внутри, не золотой диск.
s.box(-.22,.22,-.80,-.35,2.00,2.30,('#a49c73','#7d8565','#8a906b'))
for x in [-.16,.16]:
    for y in [-.72,-.42]: s.disc(x,y,2.31,.018,'#c1b693')

def chain(x,y,upper,lower):
    # Единая непрерывная цепь с редкими звеньями в той же 3D-проекции.
    s.line([(x,y,upper),(x,y,lower)],'#3c5158',3)
    s.line([(x-.012,y-.006,upper),(x-.012,y-.006,lower)],'#c2bea1',1)
    count=max(1,round((upper-lower)/.12))
    for i in range(count+1):
        z=upper-(upper-lower)*i/count
        s.disc(x,y,z,.022,'#b8b69a',normal='y' if i%2==0 else 'x')

# Раздельные грузовая ветвь и две ветви одного ручного колеса.
chain(-.12,-.34,2.02,1.76)
# Крюк физически ниже своего подвеса. Плоскость крюка вертикальна XZ.
hook=[(-.12,-.34,1.77),(-.12,-.34,1.72),(-.04,-.34,1.67),
      (.02,-.34,1.69),(.04,-.34,1.76)]
s.line(hook,'#3f5155',5); s.line(hook,'#c3b48a',3)
for x in [.02,.18]: chain(x,-.30,2.02,.90)
s.line([(.02,-.30,.90),(.04,-.30,.85),(.16,-.30,.85),(.18,-.30,.90)],'#b7b493',2)

for name,point in {'far_left':(-3,-2,.06),'far_right':(3,-2,.06),
 'near_right':(3,2,.06),'near_left':(-3,2,.06),
 'beam_ground':(0,-.7,0),'hoist_ground':(.1,-.3,0),
 'hand_chain_bottom':(.1,-.3,.85),'load_hook_bottom':(-.04,-.34,1.67),
 'trolley_pivot':(0,-.7,2.48),'ground_anchor':(0,2,0)}.items(): s.mark(name,point)
s.save('B07_vector_grid_source','Грузовое место E0, ручная таль, свободный средний пролёт, крюк поднят без груза. Непринятый параметрический исходник.')
